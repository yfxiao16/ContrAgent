"""
Generate a human-readable contracts library from the per-domain YAML configs.

Produces contracts/CONTRACTS_LIBRARY.md: every SOP contract as
(plain-English description, A/G section, LTL formula), grouped by domain, plus
the observable-atom vocabulary the contracts are written over. This is the
auditable artifact: the entire policy ContrAgent enforces, in one file.

Run:  PYTHONPATH=contragent_eval:.:../.. python live/build_library.py
"""

import glob
import os

_HERE = os.path.dirname(os.path.abspath(__file__))
_EVAL_DIR = os.path.dirname(_HERE)
CONTRACTS_DIR = os.path.join(_EVAL_DIR, "contracts")

ATOM_GLOSSARY = [
    ("called(T)", "tool T was invoked"),
    ("arg_value(T, k)", "numeric value of key k on T's call (args + grounded facts)"),
    ("succeeded", "the call returned success (side effect took place)"),
    ("prior_logged_in / prior_authenticated_admin", "observable auth state before this call"),
    ("state_<field>", "the acting user's real DB field (credit_score, balance, owed_balance, ...)"),
    ("param_<name>", "an SOP threshold from constraint_parameters"),
    (
        "state_user_exists / state_dest_user_exists",
        "the acting / destination user's row is present in the world state",
    ),
    ("state_currency_available", "the requested currency is in the exchange table"),
    ("amount_dollars", "the call amount normalised to dollars (unit-aware)"),
    (
        "gate_<g>_active / _present",
        "this task's SOP requires gate g (unconditionally / anywhere incl. OR branches)",
    ),
    (
        "gate_user_must_exist / _not_exist / dest_must_exist",
        "existence-gate polarity for this task",
    ),
    ("U (until), G (globally), -> (implies), | (or), & (and)", "finite-trace LTL operators"),
]


def _entries(ce):
    out = []
    for section, part in (("A", ce.assumption), ("G", ce.guarantee)):
        if part is None:
            continue
        for e in part if isinstance(part, list) else [part]:
            ltl = getattr(e, "ltl", None)
            if ltl is None and getattr(e, "is_structured", False):
                ltl = f"{e.pattern}({', '.join(map(str, e.args))})"
            out.append((section, ltl or getattr(e, "nl", "") or ""))
    return out


def render():
    from contragent.config import load_config

    lines = [
        "# ContrAgent SOP Contracts Library",
        "",
        "Auto-generated by `live/build_library.py` from `contracts/<domain>.yaml`.",
        "Every row is a deterministic, runtime-enforced contract authored from the",
        "domain SOP. The same contracts power offline detection and live enforcement;",
        "none reads a satisfaction verdict or the `action_should_succeed` label.",
        "",
        "## Observable atom vocabulary",
        "",
        "| atom | meaning |",
        "|---|---|",
    ]
    for a, m in ATOM_GLOSSARY:
        lines.append(f"| `{a}` | {m} |")
    lines.append("")

    total = 0
    for path in sorted(glob.glob(os.path.join(CONTRACTS_DIR, "*.yaml"))):
        domain = os.path.basename(path)[:-5]
        if domain.endswith(".live"):
            continue
        cfg = load_config(path)
        agent = cfg.agents.get("*") or next(iter(cfg.agents.values()))
        rows = []
        for ce in agent.contracts:
            desc = getattr(ce, "desc", "") or ""
            for section, ltl in _entries(ce):
                rows.append((desc, section, ltl))
        if not rows:
            continue
        total += len(rows)
        lines.append(f"## {domain}  ({len(rows)} contracts)")
        lines.append("")
        lines.append("| # | SOP rule | A/G | LTL |")
        lines.append("|---|---|---|---|")
        for i, (desc, section, ltl) in enumerate(rows, 1):
            d = desc.replace("|", "\\|")
            f = ltl.replace("|", "\\|")
            lines.append(f"| {i} | {d} | {section} | `{f}` |")
        lines.append("")

    lines.insert(
        6,
        f"**{total} contracts across {len([p for p in glob.glob(os.path.join(CONTRACTS_DIR, '*.yaml')) if not p.endswith('.live.yaml')])} domains.**\n",
    )
    out = os.path.join(CONTRACTS_DIR, "CONTRACTS_LIBRARY.md")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out, f"({total} contracts)")


if __name__ == "__main__":
    render()
